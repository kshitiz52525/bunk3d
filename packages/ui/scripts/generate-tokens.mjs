// Generates dark-only tokens from brand/tokens.json. The app is dark only;
// light values in the JSON are for print and are never emitted.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(join(here, '../../../brand/tokens.json'), 'utf8'));
const dark = (v) => (typeof v === 'string' ? v : v.dark);
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const color = Object.fromEntries(src.color.tokens.map((t) => [camel(t.name), dark(t.value)]));
const px = (s) => Number.parseFloat(s);
const radius = Object.fromEntries(src.radius.tokens.map((t) => [camel(t.name.replace('radius-', '')), px(t.value)]));
const space = Object.fromEntries(src.spacing.tokens.map((t) => [t.name.replace('space-', ''), px(t.value)]));
const tilt = Object.fromEntries(src.tilt.tokens.map((t) => [camel(t.name.replace('tilt-', '')), px(t.value)]));
const shadow = Object.fromEntries(src.shadow.tokens.map((t) => [camel(t.name.replace('shadow-', '')), dark(t.value)]));
const textStyles = {};
for (const g of src.type.groups) for (const s of g.styles) {
  textStyles[s.name] = {
    family: g.family,
    fontSize: px(s.fontSize),
    lineHeight: Math.round(px(s.fontSize) * s.lineHeight),
    fontWeight: String(s.fontWeight),
    letterSpacing: s.letterSpacing ? px(s.letterSpacing) : 0,
  };
}

const out = `// GENERATED by scripts/generate-tokens.mjs from brand/tokens.json. Do not edit.
export const color = ${JSON.stringify(color, null, 2)} as const;
export const radius = ${JSON.stringify(radius, null, 2)} as const;
export const space = ${JSON.stringify(space, null, 2)} as const;
export const tilt = ${JSON.stringify(tilt, null, 2)} as const;
export const shadow = ${JSON.stringify(shadow, null, 2)} as const;
export const textStyles = ${JSON.stringify(textStyles, null, 2)} as const;
`;
writeFileSync(join(here, '../src/tokens.generated.ts'), out);

const css = `/* GENERATED from brand/tokens.json. Dark only. */
:root {
${Object.entries(color).map(([k, v]) => `  --${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}: ${v};`).join('\n')}
${Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v}px;`).join('\n')}
${Object.entries(space).map(([k, v]) => `  --space-${k}: ${v}px;`).join('\n')}
  --shadow-sticker: ${shadow.sticker};
  --font-display: ${src.type.families.display};
  --font-sans: ${src.type.families.sans};
  color-scheme: dark;
}
`;
writeFileSync(join(here, '../src/tokens.generated.css'), css);
console.log('tokens generated');
